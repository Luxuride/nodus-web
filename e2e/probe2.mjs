import { chromium } from 'playwright'
const b = await chromium.launch(); const p = await b.newPage()
await p.addInitScript(() => localStorage.setItem('nodus-session', 'stub.instance\tstub-token'))
await p.route('**/api/v1/**', (r) => r.fulfill({ status: 200, headers: {'access-control-allow-origin':'*','content-type':'application/json'}, body: r.request().url().includes('custom_emojis') ? '[]' : '[]' }))
await p.goto('http://127.0.0.1:4173/', { waitUntil: 'load' })
await p.waitForTimeout(2500)
const box = p.locator('#nodus-composer-body')
await box.click()
await p.keyboard.type(':smi')
await p.waitForTimeout(400)
console.log('hints:', await p.locator('[data-emoji-hints] li').allInnerTexts())
await p.keyboard.press('Enter')
await p.waitForTimeout(300)
console.log('text:', await p.evaluate(() => document.querySelector('.ProseMirror')?.innerText))
await b.close()
